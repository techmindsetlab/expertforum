import { cookies } from "next/headers";
import { ADMIN_COOKIE, adminToken } from "@/lib/auth";

export async function POST(req: Request) {
  const { password } = (await req.json().catch(() => ({}))) as { password?: string };
  const expected = process.env.ADMIN_PASSWORD;
  if (!expected) return Response.json({ error: "ADMIN_PASSWORD is not configured" }, { status: 500 });
  if (password !== expected) return Response.json({ error: "Password salah" }, { status: 401 });

  (await cookies()).set(ADMIN_COOKIE, await adminToken(), {
    httpOnly: true,
    secure: process.env.NODE_ENV === "production",
    sameSite: "lax",
    path: "/",
    maxAge: 60 * 60 * 24 * 14,
  });
  return Response.json({ ok: true });
}

export async function DELETE() {
  (await cookies()).delete(ADMIN_COOKIE);
  return Response.json({ ok: true });
}
